"""Managed edge proxy: a Caddy stack in front of everything.

WhyNotHost writes its own Caddyfile (dashboard + every running app), then
runs Caddy via docker compose with ports 80/443 bound on the host. Caddy
obtains Let's Encrypt certificates automatically for public domains; for
non-resolvable local domains (*.home.arpa etc.) it falls back to `tls
internal` self-signed certificates.

Edge state layout under DATA_DIR/edge:
  compose.yaml   the edge stack definition
  Caddyfile      generated config
  caddy/data     certificates & ACME accounts (persisted across restarts)
  caddy/config   caddy adapter config
"""
import json
import re
import socket
import time

from . import store
from . import config

_SLUG_RE = re.compile(r"[^a-z0-9-]+")

# domains that can never get public LE certs (RFC 2606/6761, RFC 8375, mDNS)
_LOCAL_SUFFIXES = (
    ".local", ".arpa", ".internal", ".lan", ".home", ".test",
    ".example", ".invalid", ".localhost", ".localdomain",
)


class EdgeError(Exception):
    pass


def slugify(name: str) -> str:
    return _SLUG_RE.sub("-", name.lower()).strip("-") or "app"


def is_local_domain(domain: str) -> bool:
    d = domain.lower().rstrip(".")
    if d.endswith(".localhost") or d == "localhost":
        return True
    return any(d.endswith(s) for s in _LOCAL_SUFFIXES)


def _hostname() -> str:
    try:
        return socket.getfqdn()
    except Exception:
        return ""


def _resolves_publicly(domain: str) -> bool:
    """True if the domain resolves AND is not a reserved local suffix."""
    if is_local_domain(domain):
        return False
    try:
        return socket.gethostbyname(domain) is not None
    except OSError:
        return False


def edge_compose() -> str:
    data_dir = config.EDGE_DIR / "caddy" / "data"
    conf_dir = config.EDGE_DIR / "caddy" / "config"
    return (
        "services:\n"
        "  edge-caddy:\n"
        "    image: caddy:2-alpine\n"
        "    container_name: wnh-edge-caddy\n"
        "    network_mode: host\n"
        "    command: caddy run --config /etc/caddy/Caddyfile\n"
        "    volumes:\n"
        f"      - {config.EDGE_DIR / 'Caddyfile'}:/etc/caddy/Caddyfile:ro\n"
        f"      - {data_dir}:/data\n"
        f"      - {conf_dir}:/config\n"
        "    restart: unless-stopped\n"
    )


def generate_caddyfile() -> str:
    """Full edge Caddyfile: dashboard + all running apps.

    - public (resolving) domains -> automatic HTTPS via Let's Encrypt
    - local/reserved domains -> tls internal (self-signed)
    """
    lines = ["# Generated by WhyNotHost edge proxy — do not edit by hand", ""]

    # 1. dashboard: serve static UI + proxy /api
    lines.append("http://wnh.dashboard {")
    lines.append("    handle {")
    lines.append("        respond \"WhyNotHost dashboard — open http://<host>:8022/ui/\" 200")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    # 2. app domains
    with store.db() as conn:
        rows = conn.execute(
            "SELECT id, name, config FROM apps WHERE status = 'running'"
        ).fetchall()

    for r in rows:
        app_id = r["id"]
        cfg = json.loads(r["config"] or "{}")
        if not _web_port(cfg):
            continue  # headless daemons (e.g. ollama, tailscale) have no web UI to proxy
        domain = (cfg.get("domain") or f"{slugify(r['name'])}.{config.DOMAIN_SUFFIX}").lower()
        target = _app_target(app_id, cfg)
        lines.extend(_domain_block(domain, target))
        lines.append("")

    return "\n".join(lines)


def _app_target(app_id: str, cfg: dict) -> str:
    """Where the edge should forward traffic for an app."""
    port = _web_port(cfg)
    if port:
        return f"127.0.0.1:{port}"
    return f"{app_id}:80"


def _web_port(cfg: dict) -> str:
    """App config key holding the web-UI port ('port' or '*_port' that isn't DNS/sync)."""
    if not cfg.get("port"):
        return ""
    return cfg["port"]


def _domain_block(domain: str, target: str) -> list[str]:
    if is_local_domain(domain):
        tls = "    tls internal\n"
    else:
        tls = ""
    return [
        f"{domain} {{",
        tls +
        f"    reverse_proxy {target}",
        "}",
    ]


def write_edge_files() -> dict:
    config.EDGE_DIR.mkdir(parents=True, exist_ok=True)
    (config.EDGE_DIR / "caddy" / "data").mkdir(parents=True, exist_ok=True)
    (config.EDGE_DIR / "caddy" / "config").mkdir(parents=True, exist_ok=True)
    caddyfile = generate_caddyfile()
    (config.EDGE_DIR / "Caddyfile").write_text(caddyfile)
    (config.EDGE_DIR / "compose.yaml").write_text(edge_compose())
    # keep the legacy single-file path in sync for tooling/inspection
    config.CADDY_CONFIG_PATH.write_text(generate_caddyfile())
    return {
        "dir": str(config.EDGE_DIR),
        "caddyfile": str(config.EDGE_DIR / "Caddyfile"),
        "compose": str(config.EDGE_DIR / "compose.yaml"),
    }


def _ports_free(ports: tuple[int, ...]) -> dict[str, bool]:
    out = {}
    for p in ports:
        s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        s.settimeout(0.4)
        try:
            out[str(p)] = s.connect_ex(("127.0.0.1", p)) != 0
        finally:
            s.close()
    return out


def status() -> dict:
    d = None
    try:
        from .engine.driver import registry
        if registry.mode == "live":
            from .engine import compose_render
            d = registry.live
            running = d.status(
                "wnh-edge", str(config.EDGE_DIR)
            ).get("running", False)
        else:
            running = False
    except Exception:
        running = False

    return {
        "supported": True,
        "running": running,
        "ports_80_443_free": _ports_free((80, 443)),
        "hostname": _hostname(),
        "caddyfile": generate_caddyfile(),
        "compose": edge_compose(),
        "apps": [
            {
                "id": r["id"],
                "domain": (json.loads(r["config"] or "{}").get("domain") or f"{slugify(r['name'])}.{config.DOMAIN_SUFFIX}"),
                "https": not is_local_domain(json.loads(r["config"] or "{}").get("domain") or f"{slugify(r['name'])}.{config.DOMAIN_SUFFIX}"),
            }
            for r in _running_apps()
            if _web_port(json.loads(r["config"] or "{}"))
        ],
    }


def _running_apps() -> list:
    with store.db() as conn:
        return conn.execute(
            "SELECT id, name, config FROM apps WHERE status = 'running'"
        ).fetchall()


def enable() -> dict:
    """Write edge files and bring the Caddy stack up (live mode only)."""
    from .engine.driver import registry
    if registry.mode != "live":
        raise EdgeError("HTTPS edge requires live mode (Docker daemon unreachable)")
    files = write_edge_files()
    d = registry.live
    res = d.deploy("wnh-edge", str(config.EDGE_DIR), None)
    if not res.get("ok"):
        raise EdgeError(f"edge stack failed to start: {res.get('output', '')[:500]}")
    time.sleep(1.0)
    st = status()
    return {"ok": True, **files, "running": st["running"]}


def disable() -> dict:
    from .engine.driver import registry
    if registry.mode == "live":
        try:
            registry.live.uninstall("wnh-edge", str(config.EDGE_DIR), None)
        except Exception:
            pass
    return {"ok": True, "running": False}


def reload() -> dict:
    """Rewrite config and ask the running caddy to reload (no downtime)."""
    from .engine.driver import registry
    write_edge_files()
    if registry.mode != "live":
        return {"ok": False, "error": "not in live mode"}
    rc, out = registry.live._run_compose(
        ["exec", "-T", "edge-caddy", "caddy", "reload",
         "--config", "/etc/caddy/Caddyfile"],
        str(config.EDGE_DIR),
    )
    return {"ok": rc == 0, "output": out[-500:]}