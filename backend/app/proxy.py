"""Reverse-proxy config generation (Caddy). Each installed app with a domain
gets a block: <slug>.<suffix> -> proxy to its first published port."""
import re
import json
from pathlib import Path

from . import store
from . import config
from .config import DOMAIN_SUFFIX

_SLUG_RE = re.compile(r"[^a-z0-9-]+")


def slugify(name: str) -> str:
    return _SLUG_RE.sub("-", name.lower()).strip("-") or "app"


def _compose_ports(compose_text: str) -> list[int]:
    """Extract published host ports from a compose file (best effort YAML-lite)."""
    ports = []
    for line in compose_text.splitlines():
        s = line.strip()
        if s.startswith("- ") and (":" in s and ("127.0.0.1:" in s or s[2:].split(":")[0].isdigit() or re.match(r"^\d+:\d+", s[2:]))):
            m = re.search(r"(?:127\.0\.0\.1:)?(\d+):\d+", s)
            if m:
                ports.append(int(m.group(1)))
    return ports


def generate_caddyfile() -> str:
    lines = ["# Generated by WhyNotHost — do not edit by hand", ""]
    with store.db() as conn:
        rows = conn.execute("SELECT id, name, config FROM apps WHERE status = 'running'").fetchall()
    for r in rows:
        app_id = r["id"]
        cfg = json.loads(r["config"] or "{}")
        domain = cfg.get("domain") or f"{slugify(r['name'])}.{DOMAIN_SUFFIX}"
        stack = config.STACKS_DIR / app_id / "compose.yaml"
        ports = []
        if stack.exists():
            ports = _compose_ports(stack.read_text())
        target = f"127.0.0.1:{ports[0]}" if ports else f"{app_id}:80"
        lines.append(f"{domain} {{")
        lines.append(f"    reverse_proxy {target}")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def write_caddyfile() -> str:
    text = generate_caddyfile()
    config.CADDY_CONFIG_PATH.write_text(text)
    return str(config.CADDY_CONFIG_PATH)